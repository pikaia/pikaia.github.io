"""Generate a post's Watch widget (row markup + viewer + both <script>
blocks) from its already-authored video config, instead of hand-typing
the JS every time.

Local dev tool only - not part of the deployed Jekyll site. The video
config (scripts/video-configs/<slug>.py, see docs/production-pipeline.md
section 4) is the single source of truth for slides/schedule; this
script translates it into the JS shape the live widget needs (CSS
"50% 50%" pan strings instead of Python (0.5, 0.5) tuples, an
imageSchedule array instead of SCHEDULE tuples, etc.) and pastes in the
real sentence timings from TIMING_JSON verbatim. This removes the two
most common hand-authoring bugs from docs/production-pipeline.md's
gotchas list: the watchAudio/audio scope bug (always generated
correctly here) and Python/JS values drifting out of sync (there's only
one source now).

Does NOT require a YouTube/Shorts URL to run - a post's video is
usually rendered and reviewed before it's uploaded, so those URLs often
don't exist yet at Watch-widget-authoring time. Pass --youtube-url/
--shorts-url once they do; omit either (or both) and the row simply
gets Listen+Watch only, with a note printed to re-run once the URL(s)
exist. Re-running is always safe (idempotent) - the generated block is
wrapped in HTML comment markers so a second run replaces it in place
rather than duplicating it.

Chart and route-walk slides (see CLAUDE.md's Charts / Route animations
sections) are NOT auto-generated - their JS is structurally different
from a plain image slide (an SVG chart/route, not a background-image
div) and needs its own hand-authored buildChartSlide()/route-walk block
copied from an existing post with one. Any such slide in the config
gets a loud placeholder comment in the generated output instead of
being silently wrong.

Usage:
    python scripts/build_watch_widget.py \\
        _posts/<file>.md \\
        scripts/video-configs/<slug>.py \\
        [--youtube-url https://youtu.be/...] \\
        [--shorts-url https://youtube.com/shorts/...]
"""
