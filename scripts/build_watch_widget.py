"""Generate a post's Watch widget (row markup + viewer + both <script>
blocks) from its already-authored video config, instead of hand-typing
the JS every time.

Local dev tool only - not part of the deployed Jekyll site. The video
config (scripts/video-configs/<slug>.py, see docs/production-pipeline.md
section 4) is the single source of truth for slides/schedule; this
script translates it into the JS shape the live widget needs (CSS
"50% 50%" pan strings instead of Python (0.5, 0.5) tuples, an
imageSchedule array instead of SCHEDULE tuples, etc.) and pastes in the
real sentence timings from TIMING_JSON verbatim. This removes the two
most common hand-authoring bugs from docs/production-pipeline.md's
gotchas list: the watchAudio/audio scope bug (always generated
correctly here) and Python/JS values drifting out of sync (there's only
one source now).

Does NOT require a YouTube/Shorts URL to run - a post's video is
rendered and reviewed before it's uploaded, so those URLs never exist
yet at Watch-widget-authoring time (section 4). Omit them and the row
gets Listen+Watch only; the URLs get wired in later by re-running with
--youtube-url/--shorts-url (section 11). Re-running is always safe
(idempotent) - the generated block is wrapped in HTML comment markers
so a second run replaces it in place rather than duplicating it.

Chart slides ARE auto-generated: a `{"type": "chart", ...}` entry in
the config becomes a full `{ type: "chart", ... }` JS object plus the
generic `buildChartSlide()` SVG library, translated straight from the
config (including a small Python-format-string -> JS-formatter
converter for y_tick_format / value_format). A chart whose format
strings the converter doesn't recognise falls back to a loud MANUAL
placeholder rather than emitting broken JS. Route-walk slides are still
NOT auto-generated - their JS is more bespoke - and get the MANUAL
placeholder; hand-author those per CLAUDE.md's Route animations section.

Usage:
    python scripts/build_watch_widget.py \\
        _posts/<file>.md \\
        scripts/video-configs/<slug>.py \\
        [--youtube-url https://youtu.be/...] \\
        [--shorts-url https://youtube.com/shorts/...]
"""
