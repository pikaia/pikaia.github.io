_CHART_FMT_RE = re.compile(r'^([^{}]*)\{:(,?)\.(\d+)f\}([^{}]*)$')


def py_fmt_to_js(fmt: str) -> str | None:
    """Translate a Python number format string (a chart slide's
    y_tick_format / value_format) to a JS `function (v) { return ...; }`.
    Handles the "[prefix]{:[,].Nf}[suffix]" shape the project's chart
    configs use ("${:.0f} / sqft", "{:,.0f}", "{:.2f} children per
    woman"). Returns None for anything else so the caller can fall back
    to a MANUAL placeholder rather than emit broken JS."""
    m = _CHART_FMT_RE.match(fmt)
    if not m:
        return None
    pre, grp, prec, post = m.group(1), m.group(2), int(m.group(3)), m.group(4)
    if grp == ",":
        num = (f"v.toLocaleString('en-US', {{minimumFractionDigits: {prec}, "
               f"maximumFractionDigits: {prec}}})")
    else:
        num = f"v.toFixed({prec})"
    expr = num
    if pre:
        expr = f"{json.dumps(pre)} + " + expr
    if post:
        expr = expr + f" + {json.dumps(post)}"
    return f"function (v) {{ return {expr}; }}"


def _chart_spec_fields(d: dict) -> dict | None:
    yt = py_fmt_to_js(d.get("y_tick_format", "${:.0f}"))
    vf = py_fmt_to_js(d.get("value_format", "${:.0f} / sqft"))
    if yt is None or vf is None:
        return None
    out = {
        "data": json.dumps([list(p) for p in d["data"]]),
        "yRange": json.dumps(list(d["y_range"])),
        "yTickFormat": yt,
        "valueFormat": vf,
    }
    if "y_tick_step" in d:
        out["yTickStep"] = str(d["y_tick_step"])
    if d.get("annotations"):
        out["annotations"] = json.dumps([list(a) for a in d["annotations"]], ensure_ascii=False)
    if d.get("label"):
        out["label"] = json.dumps(d["label"], ensure_ascii=False)
    return out


def chart_slide_js(slide: dict) -> str | None:
    """Build the `{ type: "chart", ... },` JS object for one chart slide,
    from the video config's chart-slide dict. Returns None if a format
    string can't be translated (caller emits a MANUAL placeholder)."""
    top = _chart_spec_fields(slide)
    if top is None:
        return None
    lines = ['type: "chart"', f'xRange: {json.dumps(list(slide["x_range"]))}']
    if slide.get("title"):
        lines.append(f'title: {json.dumps(slide["title"], ensure_ascii=False)}')
    lines += [f"{k}: {v}" for k, v in top.items()]
    if slide.get("year_checkpoints"):
        lines.append("yearCheckpoints: "
                     + json.dumps([list(c) for c in slide["year_checkpoints"]]))
    if "series2" in slide:
        s2 = _chart_spec_fields(slide["series2"])
        if s2 is None:
            return None
        lines.append("series2: { "
                     + ", ".join(f"{k}: {v}" for k, v in s2.items()) + " }")
    return "{\n      " + ",\n      ".join(lines) + "\n    },"


JS_IDENTIFIER_RE = re.compile(r'^[A-Za-z_$][A-Za-z0-9_$]*$')


def build_watch_script(cfg, slug: str) -> tuple[str, int, bool]:
    images_by_key = cfg.IMAGES
    for key in images_by_key:
        if not JS_IDENTIFIER_RE.match(key):
            # Every IMAGES key becomes a bare `var KEY = "url";` and a bare
            # `src: KEY` reference in the generated JS - not a valid target
            # for arbitrary strings the way a Python dict key is. Caught for
            # real: an auto-derived key starting with a digit ("2005...")
            # produced `var 2005... = ...;`, invalid JS that node --check
            # rejects outright. Fail loudly here rather than ship it.
            raise ValueError(
                f'IMAGES key {key!r} in {cfg.__name__} is not a valid JS identifier '
                f'(used as `var {key} = ...;` in the generated widget script) - '
                f'rename it to something like {"IMG_" + key if key else "IMG1"!r}.'
            )
    image_lines = [f'  var {key} = "{url}";' for key, url in images_by_key.items()]

    slide_lines, manual_count, has_chart = build_slides_js(cfg, images_by_key)
    slides_block = "  var slides = [\n    " + "\n    ".join(slide_lines) + "\n  ];"

    timing_path = REPO_ROOT / cfg.TIMING_JSON
    sentences = json.loads(timing_path.read_text(encoding="utf-8"))
    sentences_line = "  var sentences = " + json.dumps(sentences, ensure_ascii=False) + ";"

    schedule_lines = ", ".join(f"{{ t: {t}, slide: {s} }}" for t, s in cfg.SCHEDULE)
    schedule_block = "  var imageSchedule = [\n    " + schedule_lines + "\n  ];"

    header = (
        "<script>\n(function () {\n"
        + "\n".join(image_lines) + "\n\n"
        + slides_block + "\n\n"
        + sentences_line + "\n\n"
        + schedule_block + "\n"
        + f"  var TOTAL_DURATION = {cfg.TOTAL_DURATION};\n"
    )
    tail = WATCH_SCRIPT_TAIL.replace(
        "__CHART_LIB__\n", (CHART_LIB_JS + "\n") if has_chart else "")
    return header + tail, manual_count, has_chart


def find_existing_urls(text: str) -> tuple[str | None, str | None]:
    main_url, short_url = None, None
    for m in re.finditer(r'href="(https://(?:youtu\.be|(?:www\.)?youtube\.com)/[^"]+)"', text):
        url = m.group(1)
        if "/shorts/" in url:
            short_url = short_url or url
        else:
            main_url = main_url or url
    return main_url, short_url


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("post_path")
    ap.add_argument("config_path", help="scripts/video-configs/<slug>.py")
    ap.add_argument("--youtube-url", default=None)
    ap.add_argument("--shorts-url", default=None)
    args = ap.parse_args()

    post_path = Path(args.post_path)
    config_path = Path(args.config_path)
    slug = config_path.stem

    cfg = load_config(config_path)
    post_text = post_path.read_text(encoding="utf-8")

    # A URL already wired into the post (e.g. from a previous run) is
    # preserved even if this run doesn't pass --youtube-url/--shorts-url
    # again - re-running to pick up ONE new URL shouldn't blank the other.
    existing_youtube, existing_shorts = find_existing_urls(post_text)
    youtube_url = args.youtube_url or existing_youtube
    shorts_url = args.shorts_url or existing_shorts

    grad_id = gradient_id(slug)
    row_markup = build_row_markup(youtube_url, shorts_url, grad_id)
    watch_script, manual_count, _has_chart = build_watch_script(cfg, slug)

    block = "\n\n".join([
        MARKER_BEGIN,
        row_markup,
        (f'<audio id="listen-audio" preload="none" style="display: none;">\n'
         f'  <source src="{audio_web_path(cfg)}" type="audio/mpeg">\n'
         f'</audio>'),
        VIEWER_MARKUP,
        LISTEN_SCRIPT,
        watch_script,
        MARKER_END,
    ])

    has_markers = MARKER_BEGIN in post_text and MARKER_END in post_text
    has_watch_widget = 'id="watch-widget"' in post_text
    has_listen_widget = 'id="listen-widget"' in post_text

    if has_markers:
        pattern = re.compile(re.escape(MARKER_BEGIN) + r".*?" + re.escape(MARKER_END), re.DOTALL)
        # A callable replacement, not a raw string - `block` contains
        # literal backslashes (the JS caption chunker's \s+ regex), and
        # re.sub treats a *string* replacement's backslashes as
        # backreference escapes (\1 etc.), raising "bad escape \s" here.
        # A function is substituted verbatim with no such processing.
        new_text = pattern.sub(lambda _m: block, post_text, count=1)
        mode = "updated"
    elif has_watch_widget:
        print(f"ERROR: {post_path} already has a Watch widget that wasn't generated by this "
              f"script (no marker comments found), so it may carry hand-tuned data this script "
              f"can't tell apart from a stale duplicate. Refusing to touch it automatically - "
              f"remove the existing widget by hand first, or add the marker comments around it "
              f"yourself, then re-run.", file=sys.stderr)
        sys.exit(1)
    elif has_listen_widget:
        # Every post already got a bare Listen-only widget from the
        # site-wide rollout (scripts/insert_listen_widget.py) - this is
        # the expected, common starting point for adding a Watch widget,
        # not an unmanaged edge case. Safe to replace: that template's
        # shape is a single <div id="listen-widget">...</div> (with its
        # own nested <audio>) immediately followed by its one <script>
        # block - matched here from the div open to that script's close.
        bare_re = re.compile(r'<div id="listen-widget".*?</script>', re.DOTALL)
        m = bare_re.search(post_text)
        if not m:
            print(f"ERROR: found id=\"listen-widget\" in {post_path} but couldn't isolate its "
                  f"exact block boundaries (unexpected markup shape) - refusing to guess. Remove "
                  f"it by hand first, or add the marker comments around it yourself.",
                  file=sys.stderr)
            sys.exit(1)
        new_text = post_text[:m.start()] + block + post_text[m.end():]
        mode = "upgraded from Listen-only to"
    else:
        idx = post_text.find(BACK_LINK_LINE)
        if idx == -1:
            print(f"ERROR: no '{BACK_LINK_LINE}' line found in {post_path} - can't find where "
                  f"to insert the widget.", file=sys.stderr)
            sys.exit(1)
        insert_at = idx + len(BACK_LINK_LINE)
        new_text = post_text[:insert_at] + "\n\n" + block + post_text[insert_at:]
        mode = "inserted"

    post_path.write_text(new_text, encoding="utf-8")
    print(f"OK: {mode} Watch widget in {post_path}", file=sys.stderr)

    if manual_count:
        print(f"NOTE: {manual_count} slide(s) need manual authoring (route-walk, or a chart "
              f"whose format strings this script can't convert) - search the file for "
              f"'MANUAL:' comments.", file=sys.stderr)


if __name__ == "__main__":
    main()
