def load_config(config_path: Path):
    spec = importlib.util.spec_from_file_location(config_path.stem, config_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def fmt_pct(fraction: float) -> str:
    """0.45 -> "45%", 0.671 -> "67.1%" - matches the CSS background-position
    percentage strings the live widget's JS expects (never Python's
    0-1 float tuples, which are for the PIL renderer only)."""
    pct = fraction * 100
    return f"{pct:g}%"


def js_pan(pan: tuple) -> str:
    return f'"{fmt_pct(pan[0])} {fmt_pct(pan[1])}"'


def audio_web_path(cfg) -> str:
    """The <audio> tag's web-facing src, derived from TIMING_JSON's own
    basename - NOT from the slug/config filename. Most posts' audio
    happens to share the config's slug, but a few (e.g. a post that was
    A/B-tested between TTS engines) keep a differently-suffixed filename
    as canonical (jalan-payoh-lai-kangkar-montfort-nativity-church's
    real audio is ...-kokoro.mp3, not the bare slug). Deriving from
    TIMING_JSON matches watch_video_lib.py's render() and guarantees the
    widget's audio always matches the sentence timings it's driven by -
    the two can never legitimately point at different files.

    Pure string manipulation, deliberately NOT pathlib.Path - this is a
    web URL, always forward-slashed, and Path() on Windows renders with
    backslashes (a real bug caught by the diff-audit: it produced
    "/audio\\foo.mp3" instead of "/audio/foo.mp3")."""
    tj = cfg.TIMING_JSON
    base = tj[: -len(".timing.json")] if tj.endswith(".timing.json") else tj.rsplit(".", 1)[0]
    return "/" + base + ".mp3"


def gradient_id(slug: str) -> str:
    """A per-post-unique SVG gradient id for the Shorts icon - collisions
    only matter if two posts' widgets ever render in the same DOM (not
    currently possible on this site), but the convention costs nothing."""
    words = re.sub(r"[^a-zA-Z0-9]", " ", slug).split()
    camel = "".join(w.capitalize() for w in words[:3])
    digest = hashlib.md5(slug.encode("utf-8")).hexdigest()[:4]
    return f"shortsGrad{camel}{digest}"


def build_slides_js(cfg, images_by_key: dict) -> tuple[list[str], int]:
    """Returns (lines, manual_count). Each SLIDES entry with an "img" key
    becomes a real { src: KEY, ... } JS object; anything else (chart,
    route-walk) becomes a flagged placeholder that still parses as valid
    JS (falls back to the post's own hero image) so the file doesn't
    break, but is unmistakably not the real slide."""
    lines = []
    manual_count = 0
    hero_key = next(iter(images_by_key), None)
    for i, slide in enumerate(cfg.SLIDES):
        key = slide.get("img")
        if key is None:
            manual_count += 1
            slide_type = slide.get("type", "unknown")
            comment = (f'/* MANUAL: slide {i} is type "{slide_type}" in the video config - '
                       f'auto-generation only covers cover/letterbox. Hand-author this slide '
                       f"per CLAUDE.md's Charts/Route animations section, copying the pattern "
                       f"from an existing post with one. Placeholder below just reuses the "
                       f"hero image so the widget still loads. */")
            lines.append(comment)
            lines.append(
                f'{{ src: {hero_key}, type: "cover", zoom: [1, 1, 1], '
                f'pan: ["50% 50%", "50% 50%", "50% 50%"], ease: "linear" }},'
            )
            continue
        zoom = json.dumps(slide["zoom"])
        pans = ", ".join(js_pan(p) for p in slide["pan"])
        ease = slide.get("ease", "ease-in-out")
        lines.append(
            f'{{ src: {key}, type: "{slide["type"]}", zoom: {zoom}, pan: [{pans}], ease: "{ease}" }},'
        )
    return lines, manual_count


